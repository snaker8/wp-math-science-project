// 수식 환경 안쪽에 섞여 들어온 $ 제거
// ============================================================================
//
// ★ 사고 (2026-08-31, 서여고 미적분1 실측)
//   Mathpix 가 연립방정식 두 줄 중 아랫줄만 $ 로 감싸서 내보내는 경우가 있다.
//   그 상태로 전체를 $$ 로 감싸면 수식 모드 안에 $ 가 남아 KaTeX 가 통째로 실패하고,
//   화면에는 cases 원문이 날것(LaTeX 문자열)으로 그대로 노출된다.
//   사용자 신고: "이거 원래 잘 인식했는데 왜 이렇지?"
//
//   cases·array·aligned 같은 수식 환경 **안에서 $ 는 어떤 경우에도 유효한 문법이 아니다.**
//   따라서 남아 있으면 OCR/생성 산출물의 결함이고, 걷어내는 것이 항상 옳다.
//
//   [원인 조사] 우리 쪽 Mathpix 설정(math_inline_delimiters)은 초기 이후 바뀐 적이 없고,
//   4~7월 DB 의 cases 문제 164건에는 이 형태가 한 건도 없었다(실측). 즉 Mathpix 산출물
//   쪽 변화로 보이나, 8월 표본이 0이라 시점은 특정 못 한다.
//   → 그래서 "언제 어떤 모델이 만들었든" 무해하게 동작하는 정규화로 막는다.
//
// ★ .tsx 는 vitest(jsx:"preserve")에서 import 되지 않아 기존 렌더러 테스트들은 구현을
//   복제해 검증한다. 복제본은 실제 회귀를 못 잡으므로 이 로직만 .ts 로 분리했다.

/**
 * `\begin{env}…\end{env}` 한 덩어리에서 `$` 를 전부 제거한다.
 *
 * 호출측(MixedContentRenderer 1-4 단계)은 이미 "이 환경이 $ 블록 **바깥**에 있다"고
 * 판정한 상태에서만 부른다. 즉 여기 남아 있는 $ 는 전부 환경 내부의 잘못된 구분자다.
 *
 * @param mathEnv `\begin{...}` 부터 `\end{...}` 까지의 원문
 * @returns $ 를 걷어낸 원문 (그 외 내용은 손대지 않는다)
 */
export function stripDollarsInsideMathEnv(mathEnv: string): string {
  return mathEnv.replace(/\$+/g, '');
}

// ============================================================================
// OCR 출력 깨진 LaTeX 자산화 시점 정정 (2026-05-19)
//
// 배경: BS_H1S2_R2 1번 사고 — Mathpix OCR 가 한글 라벨((가)/(나)/(ㄱ)/(ㄴ))을
//       `$(가)$` / `=$(ㄴ)$\\` 같이 잘못 wrap 또는 라인 끝 `\\` 잔여로 출력.
//       자산화 시점에 자동 정정해서 DB content_latex 에 깨진 raw 박힘 차단.
//
// 정책: 매우 보수적 패턴만 정정 — 정상 LaTeX 영향 없는 케이스 한정.
//       애매한 패턴 (예: `=$X$` 의 `=`-`$` 합치기) 는 광역 회귀 위험 커서 제외.
// ============================================================================

/**
 * OCR 출력의 깨진 LaTeX 패턴을 자산화 시점에 정정.
 *
 * 정정 패턴:
 *  1. `$(한글)$` — 단독 한글/자모 라벨이 inline-math 로 wrap → 벗기기
 *     예: `$(가)$` → `(가)`, `$(ㄴ)$` → `(ㄴ)`
 *  2. `=$(한글)$\\` — 수식 끝 `=` 직후 잘못된 `$` 분리 + 라벨 + 라인 끝 `\\` 잔여
 *     → `=` 와 라벨을 수식 안으로 통합 (수식 닫는 `$` 위치 정정)
 *     예: `$2(...)=$(ㄴ)$\\` → `$2(...)=(ㄴ)$`
 *  3. 수식 닫힘 직후 라인 끝 `\\` + 다음 라인 한글 시작 — `\\` 제거
 *     예: `...$\\<개행>(가)` → `...$<개행>(가)`
 *
 * 회귀 안전성:
 *  - 패턴 1: 한글이 inline-math 안 있는 경우는 OCR 오류로 간주 (정상 LaTeX 에 단독 한글 wrap 없음)
 *  - 패턴 2: `=` 직후 `$` + 한글 라벨 + `$\\` 의 매우 특정한 형식만 매치
 *  - 패턴 3: 수식 닫는 `$` 직후 라인 끝 `\\` + 다음 라인 한글 시작 한정
 */
export function repairOcrBrokenLatex(content: string): string {
  if (!content) return content;
  let result = content;

  // ─── 패턴 1: $(한글)$ inline-math wrap 해제 ───
  //   정상 LaTeX 에 단독 한글만 든 inline-math 케이스 없음. 안전.
  //   `(가)`, `(ㄴ)`, `(가나다)` 등 한글/자모 + 선택적 공백·쉼표.
  result = result.replace(/\$\(([ㄱ-ㅎ가-힣\s,]+)\)\$/g, '($1)');

  // ─── 패턴 2: `=$(라벨)$\\` 형태 정정 ───
  //   수식 안에서 `=` 직후 `$` 가 잘못 닫히고 한글 라벨 + `$\\` 잔여.
  //   원본 의도: `$expr=(라벨)$` (라벨도 수식 안). `\\` 는 라인 끝 잔여.
  //   매치 조건: `=$` 다음 한글 only 라벨 `()` 다음 `$\\` 라인 끝.
  result = result.replace(
    /=\$\(([ㄱ-ㅎ가-힣\s,]+)\)\$\\\\(?=\s*\n|\s*$)/g,
    (_m, label: string) => `=(${label})$`
  );

  // ─── 패턴 3: 수식 닫힘 직후 라인 끝 `\\` 제거 ───
  //   `text$\\<개행>` 형식에서 `\\` 는 LaTeX 줄바꿈 의미 — 수식 밖에서는 무효.
  //   다음 라인이 한글로 시작하는 경우만 정정 (정상 LaTeX block 보호).
  result = result.replace(/(\$)\\\\(\s*\n\s*[가-힣(\[])/g, '$1$2');

  return result;
}

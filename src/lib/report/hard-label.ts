// ============================================================================
// 「고난도 문항」 표현 — 시험지 난이도에 맞춘다 (2026-10-17 대표: "중등에서 난이도 3~5 문항을 고난도라 하긴 그렇다")
//   수학비서 1~10 척도: 뽑힌 문항 중 최고 난이도가 7 이상이면 「고난도 문항」, 아니면 「변별 문항」(등급을 가르는 문항).
//   리포트(공유·대시보드)·프롬프트가 같은 함수를 쓴다.
// ============================================================================
export function hardQuestionLabel(maxDifficulty: number | null | undefined): '고난도 문항' | '변별 문항' {
  return (maxDifficulty ?? 0) >= 7 ? '고난도 문항' : '변별 문항';
}
